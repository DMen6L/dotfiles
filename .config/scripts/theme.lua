local function render_state(id)
	return 'return {\n\tactive = "' .. id .. '",\n}\n'
end

local function output_files(selected)
	return {
		{ path = root .. "/Quickshell/theme/Colors.qml", content = render_quickshell(selected) },
		{ path = root .. "/hypr/modules/theme.lua", content = render_hypr(selected) },
		{ path = root .. "/rofi/shared/colors.rasi", content = render_rofi(selected) },
		{ path = root .. "/swaync/colors/active.css", content = render_swaync(selected) },
		{ path = root .. "/kitty/themes/active.conf", content = render_kitty(selected) },
		{ path = root .. "/starship/starship.toml", content = render_starship(selected) },
		{ path = root .. "/fastfetch/config.jsonc", content = render_fastfetch(selected) },
		{ path = root .. "/starship/zsh-theme.zsh", content = render_zsh_highlighting(selected) },
	}
end

local function apply_theme(id)
	local selected = theme.resolve(id)
	for _, output in ipairs(output_files(selected)) do
		write_atomic(output.path, output.content)
	end

	write_atomic(root .. "/assets/theme_state.lua", render_state(selected.id))
	print("Applied theme: " .. selected.name .. " (" .. selected.id .. ")")

	local hypr_ok = os.execute("hyprctl reload >/dev/null 2>&1")
	if hypr_ok then
		print("Reloaded Hyprland")
	else
		io.stderr:write("Theme files generated; Hyprland reload skipped.\n")
	end

	local swaync_ok = os.execute("swaync-client -rs >/dev/null 2>&1")
	if swaync_ok then
		print("Reloaded SwayNC CSS")
	else
		io.stderr:write("Theme files generated; SwayNC CSS reload skipped.\n")
	end

	print("Quickshell reloads its generated colors automatically. New Kitty windows use the active theme.")
end

local function print_usage()
	io.stderr:write("Usage: lua scripts/theme.lua <list|current|apply> [theme-id]\n")
end

local command = arg[1]
if command == "list" then
	local active = theme.current().id
	local ids = {}
	for id in pairs(theme.profiles()) do
		table.insert(ids, id)
	end
	table.sort(ids)
	for _, id in ipairs(ids) do
		local profile = theme.resolve(id)
		print((id == active and "* " or "  ") .. id .. " — " .. profile.name)
	end
elseif command == "current" then
	local selected = theme.current()
	print(selected.id .. " — " .. selected.name)
elseif command == "apply" and arg[2] then
	local ok, error_message = pcall(apply_theme, arg[2])
	if not ok then
		io.stderr:write("Theme apply failed: " .. tostring(error_message) .. "\n")
		os.exit(1)
	end
else
	print_usage()
	os.exit(1)
end
