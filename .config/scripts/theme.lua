local function render_kitty(selected)
	if selected.visuals.kittyThemeFile then
		-- The themes kitten installs the official theme; keep Kitty's own definitions.
		read_file(root .. "/kitty/" .. selected.visuals.kittyThemeFile)
		return "# Generated by scripts/theme.lua. Do not edit by hand.\n"
			.. "include ../" .. selected.visuals.kittyThemeFile .. "\n"
	end
	local terminal = selected.terminal
	local lines = {
		"# Generated by scripts/theme.lua. Do not edit by hand.",
		"background " .. hex(terminal.background),
		"foreground " .. hex(terminal.foreground),
		"cursor " .. hex(terminal.cursor),
		"cursor_text_color " .. hex(terminal.cursorText),
		"selection_background " .. hex(terminal.selectionBackground),
		"selection_foreground " .. hex(terminal.selectionForeground),
		"",
	}

	for index, color in ipairs(terminal.normal) do
		table.insert(lines, "color" .. (index - 1) .. " " .. hex(color))
	end

	table.insert(lines, "")
	for index, color in ipairs(terminal.bright) do
		table.insert(lines, "color" .. (index + 7) .. " " .. hex(color))
	end

	return table.concat(lines, "\n") .. "\n"
end

local function render_starship(selected)
	local starship_role_names = {
		panelAlt = "panel_alt",
		accentAlt = "accent_alt",
		ornamentText = "ornament_text",
		runtimeNode = "runtime_node",
		runtimePython = "runtime_python",
		runtimeRust = "runtime_rust",
		runtimeGo = "runtime_go",
		runtimeLua = "runtime_lua",
	}
	local palette_lines = {}
	for _, entry in ipairs(color_entries(selected)) do
		local name = starship_role_names[entry.name] or entry.name
		table.insert(palette_lines, name .. ' = "' .. hex(entry.color) .. '"')
	end

	local prompt_colors = {
		{ name = "prompt_identity_bg", role = "promptIdentity" },
		{ name = "prompt_identity_text", role = "promptIdentityText" },
		{ name = "prompt_directory_bg", role = "promptDirectory" },
		{ name = "prompt_directory_text", role = "promptDirectoryText" },
	}
	for _, prompt_color in ipairs(prompt_colors) do
		local color = selected.colors[prompt_color.role]
		assert(color and color.hex, "missing Starship prompt color: " .. prompt_color.role)
		table.insert(palette_lines, prompt_color.name .. ' = "' .. hex(color) .. '"')
	end

	local layout = read_file(root .. "/starship/layout.toml")
	local output, replacements = layout:gsub("__THEME_PALETTE__", table.concat(palette_lines, "\n"))
	assert(replacements == 1, "starship layout must contain exactly one __THEME_PALETTE__ marker")
	return output
end

local function fastfetch_palette_swatches(selected)
	local palette = selected.palette
	local swatch_rows = selected.visuals.fastfetchSwatches or {
		{ "base00", "base01", "base02", "base03", "base04", "base05", "base06", "base07" },
		{ "error", "tertiary_container", "base0a", "base0b", "primary", "primary_container", "tertiary", "base0f" },
	}
	local rows = {}

	for row_index, swatch_row in ipairs(swatch_rows) do
		local swatches = {}
		for _, palette_key in ipairs(swatch_row) do
			local color = palette[palette_key]
			assert(color and color.hex, "missing Fastfetch palette color: " .. palette_key)
			table.insert(swatches, "{#" .. hex(color) .. "}██")
		end
		rows[row_index] = table.concat(swatches)
	end

	return rows
end

local function render_fastfetch(selected)
	local colors = selected.colors
	local swatch_rows = fastfetch_palette_swatches(selected)
	local replacements = {
		{ marker = "__FASTFETCH_ACCENT__", value = hex(colors.accent) },
		{ marker = "__FASTFETCH_ACCENT_ALT__", value = hex(colors.accentAlt) },
		{ marker = "__FASTFETCH_TEXT__", value = hex(colors.text) },
		{ marker = "__FASTFETCH_MUTED__", value = hex(colors.muted) },
		{ marker = "__FASTFETCH_SUCCESS__", value = hex(colors.success) },
		{ marker = "__FASTFETCH_PALETTE_TOP__", value = swatch_rows[1] },
		{ marker = "__FASTFETCH_PALETTE_BOTTOM__", value = swatch_rows[2] },
	}

	local output = read_file(root .. "/fastfetch/layout.jsonc")
	for _, replacement in ipairs(replacements) do
		local count
		output, count = output:gsub(replacement.marker, replacement.value)
		assert(count > 0, "fastfetch layout is missing marker: " .. replacement.marker)
	end

	return output
end

