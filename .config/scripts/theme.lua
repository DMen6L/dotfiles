local function apply_theme(id, reload)
	local selected = theme.resolve(id)
	for _, output in ipairs(output_files(selected)) do
		write_atomic(output.path, output.content)
	end

	write_atomic(root .. "/assets/theme_state.lua", render_state(selected.id))
	print("Applied theme: " .. selected.name .. " (" .. selected.id .. ")")

	if not reload then
		return
	end

	local gtk_theme = selected.visuals.gtkTheme or "Adwaita"
	local gtk_color_scheme = selected.visuals.gtkColorScheme or "default"
	local gtk_ok = os.execute("gsettings set org.gnome.desktop.interface gtk-theme " .. shell_quote(gtk_theme)
		.. " && gsettings set org.gnome.desktop.interface color-scheme " .. shell_quote(gtk_color_scheme))
	if gtk_ok then
		print("Applied GTK preferences")
	else
		io.stderr:write("GTK config generated; desktop settings update skipped.\n")
	end

	local hypr_ok = os.execute("hyprctl reload >/dev/null 2>&1")
	if hypr_ok then
		print("Reloaded Hyprland")
	else
		io.stderr:write("Theme files generated; Hyprland reload skipped.\n")
	end

	local swaync_ok = os.execute("swaync-client -rs >/dev/null 2>&1")
	if swaync_ok then
		print("Reloaded SwayNC CSS")
	else
		io.stderr:write("Theme files generated; SwayNC CSS reload skipped.\n")
	end

	print("Waybar and Quickshell reload their generated colors automatically. New Kitty windows use the active theme.")
end

local function print_usage()
	io.stderr:write("Usage: lua scripts/theme.lua <list|current|apply> [theme-id] [--no-reload]\n")
end

local command = arg[1]
if command == "list" then
	local active = theme.current().id
	local ids = {}
	for id in pairs(theme.profiles()) do
		table.insert(ids, id)
	end
	table.sort(ids)
	for _, id in ipairs(ids) do
		local profile = theme.resolve(id)
		print((id == active and "* " or "  ") .. id .. " — " .. profile.name)
	end
elseif command == "current" then
	local selected = theme.current()
	print(selected.id .. " — " .. selected.name)
elseif command == "apply" and arg[2] then
	local ok, error_message = pcall(apply_theme, arg[2], arg[3] ~= "--no-reload")
	if not ok then
		io.stderr:write("Theme apply failed: " .. tostring(error_message) .. "\n")
		os.exit(1)
	end
else
	print_usage()
	os.exit(1)
end
