local function render_gtk4_css(selected)
	local lines = "/* Generated by scripts/theme.lua. Do not edit by hand. */\n"
	if selected.visuals.gtkTheme then
		local data_root = os.getenv("XDG_DATA_HOME") or (assert(os.getenv("HOME")) .. "/.local/share")
		local stylesheet = data_root .. "/themes/" .. selected.visuals.gtkTheme .. "/gtk-4.0/gtk.css"
		for _, version in ipairs({ "gtk-3.0", "gtk-4.0" }) do
			local path = data_root .. "/themes/" .. selected.visuals.gtkTheme .. "/" .. version .. "/gtk.css"
			local file = io.open(path, "r")
			assert(file, "GTK theme is not installed: " .. path)
			file:close()
		end
		lines = lines .. '@import url("' .. stylesheet .. '");\n'
	end
	return lines
end

