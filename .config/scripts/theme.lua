local function config_root()
	return os.getenv("XDG_CONFIG_HOME") or (assert(os.getenv("HOME"), "HOME is not set") .. "/.config")
end

local root = config_root()
package.path = table.concat({
	root .. "/assets/?.lua",
	root .. "/assets/?/init.lua",
	package.path,
}, ";")

