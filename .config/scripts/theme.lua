local function shell_quote(value)
	return "'" .. value:gsub("'", "'\\''") .. "'"
end

local function ensure_directory(path)
	local ok, _, code = os.execute("mkdir -p " .. shell_quote(path))
	assert(ok, "could not create directory '" .. path .. "' (exit " .. tostring(code) .. ")")
end

local function write_atomic(path, content)
	local directory = path:match("^(.*)/[^/]+$")
	assert(directory, "path has no directory: " .. path)
	ensure_directory(directory)

	local temporary = path .. ".tmp"
	local file, error_message = io.open(temporary, "w")
	assert(file, error_message)
	file:write(content)
	file:close()

	assert(os.rename(temporary, path), "could not replace " .. path)
end

local function hex(color)
	return color.hex
end

-- Export functional roles and the full native palette without name collisions.
local function color_entries(selected)
	local entries = {}
	for _, role in ipairs(role_order) do
		table.insert(entries, { name = role, color = selected.colors[role] })
	end
	local names = {}
	for name, color in pairs(selected.palette) do
		if type(color) == "table" and color.hex then
			table.insert(names, name)
		end
	end
	table.sort(names)
	for _, name in ipairs(names) do
		table.insert(entries, { name = "palette_" .. name, color = selected.palette[name] })
	end
	return entries
end

local function read_file(path)
	local file, error_message = io.open(path, "r")
	assert(file, error_message)

	local content = file:read("*a")
	file:close()
	return content
end

local function render_quickshell(selected)
	local lines = {
		"pragma Singleton",
		"",
		"import QtQuick",
		"",
		"// Generated by scripts/theme.lua. Do not edit by hand.",
		"QtObject {",
	}

	for _, entry in ipairs(color_entries(selected)) do
		table.insert(lines, "    readonly property color " .. entry.name .. ': "' .. hex(entry.color) .. '"')
	end

	table.insert(lines, "}")
	return table.concat(lines, "\n") .. "\n"
end

local function render_hypr(selected)
	local lines = {
		"-- Generated by scripts/theme.lua. Do not edit by hand.",
		"local theme = {",
	}

	for _, entry in ipairs(color_entries(selected)) do
		table.insert(lines, "\t" .. entry.name .. ' = { hex = "' .. hex(entry.color) .. '" },')
	end

	table.insert(lines, "}")
	table.insert(lines, "")
	table.insert(lines, "function theme.hex(name)")
	table.insert(lines, "\tassert(theme[name] and theme[name].hex, \"unknown theme role: \" .. tostring(name))")
	table.insert(lines, "\treturn theme[name].hex")
	table.insert(lines, "end")
	table.insert(lines, "")
	table.insert(lines, "function theme.rgba(name, alpha)")
	table.insert(lines, "\tlocal value = theme.hex(name):sub(2)")
	table.insert(lines, "\tlocal aa = (\"%02x\"):format(math.floor(alpha * 255 + 0.5))")
	table.insert(lines, "\treturn \"rgba(\" .. value .. aa .. \")\"")
	table.insert(lines, "end")
	table.insert(lines, "")
	table.insert(lines, "function theme.argb(name, alpha)")
	table.insert(lines, "\tlocal value = theme.hex(name):sub(2)")
	table.insert(lines, "\tlocal aa = (\"%02x\"):format(math.floor(alpha * 255 + 0.5))")
	table.insert(lines, "\treturn tonumber(\"0x\" .. aa .. value)")
	table.insert(lines, "end")
	table.insert(lines, "")
	table.insert(lines, "return theme")
	return table.concat(lines, "\n") .. "\n"
end

local function render_rofi(selected)
	local lines = { "/* Generated by scripts/theme.lua. Do not edit by hand. */", "* {" }
	for _, entry in ipairs(color_entries(selected)) do
		-- Rasi identifiers accept hyphens but not underscores.
		table.insert(lines, "  " .. entry.name:gsub("_", "-") .. ": " .. hex(entry.color) .. "FF;")
	end
	local aliases = {
		{ "background-alt", "panel" }, { "foreground", "text" },
		{ "selected", "accent" }, { "active", "success" },
	}
	for _, alias in ipairs(aliases) do
		table.insert(lines, "  " .. alias[1] .. ": " .. hex(selected.colors[alias[2]]) .. "FF;")
	end
	table.insert(lines, "}")
	return table.concat(lines, "\n") .. "\n"
end

local function render_swaync(selected)
	local colors = selected.colors
	local lines = { "/* Generated by scripts/theme.lua. Do not edit by hand. */" }
	for _, entry in ipairs(color_entries(selected)) do
		table.insert(lines, "@define-color " .. entry.name .. " " .. hex(entry.color) .. ";")
	end
	local aliases = {
		{ "bg0_h", colors.panel }, { "bg0", colors.background },
		{ "bg1", colors.panel }, { "bg2", colors.panelAlt },
		{ "bg3", selected.palette.surface1 or colors.muted },
		{ "bg4", selected.palette.surface2 or colors.muted },
		{ "fg", colors.text }, { "fg0", colors.text }, { "fg1", colors.text },
		{ "fg4", colors.muted }, { "aqua", colors.audio },
		{ "green", colors.success }, { "gray", colors.muted },
		{ "blue", selected.palette.blue or colors.info },
		{ "yellow", colors.warning }, { "red", colors.urgent },
		{ "ornament", colors.ornamentText },
	}
	for _, alias in ipairs(aliases) do
		table.insert(lines, "@define-color " .. alias[1] .. " " .. hex(alias[2]) .. ";")
	end
	return table.concat(lines, "\n") .. "\n"
end

